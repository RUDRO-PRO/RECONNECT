const { test } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { MongoMemoryReplSet } = require('mongodb-memory-server');
const { createApp } = require('../server');
const User = require('../models/User');
const Team = require('../models/Team');
test('OTP lifecycle and private team collaboration', async t => {
  const db = await MongoMemoryReplSet.create({ replSet: { count: 1 } });
  await mongoose.connect(db.getUri()); await User.init();
  const mail = []; let rejectMail = false;
  const app = createApp({ secret: 'workspace-test-secret-longer-than-32-characters', clientId: '', resolveMx: async () => [{ exchange: 'mx.example.com' }], mailer: { async sendMail(message) { if (rejectMail) throw Error('SMTP'); mail.push(message); return {}; } } });
  const server = app.listen(0, '127.0.0.1'); await new Promise(r => server.once('listening', r));
  t.after(async () => { await new Promise(r => server.close(r)); await mongoose.disconnect(); await db.stop(); });
  const request = async (path, body, token, method = body ? 'POST' : 'GET') => {
    const res = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: res.status, data: await res.json() };
  };
  const email = 'builder@example.com', body = { email, fullName: 'Builder', password: 'secure-password' };
  const registration = await request('/auth/register', body);
  assert.equal(registration.status, 201); assert.equal(registration.data.token, undefined);
  const otp = mail.at(-1).text.match(/\b\d{6}\b/)[0];
  const stored = await User.findOne({ email }).select('+verificationOtpHash +verificationOtpExpires');
  assert.notEqual(stored.verificationOtpHash, otp); assert.equal(stored.isVerified, false);
  assert.ok(stored.verificationOtpExpires > Date.now());
  assert.equal((await request('/auth/login', body)).data.code, 'EMAIL_NOT_VERIFIED'); assert.equal(mail.length, 1);
  assert.equal((await request('/auth/resend-verification', { email })).status, 429);
  assert.equal((await request('/auth/verify-email', { email, otp: '000000' })).status, 400);
  const verified = await request('/auth/verify-email', { email, otp }); assert.equal(verified.status, 200);
  assert.ok(verified.data.token); assert.equal((await request('/auth/verify-email', { email, otp })).status, 400);
  assert.equal((await User.findOne({ email }).select('+verificationOtpHash')).verificationOtpHash, undefined);
  const otherEmail = 'other@example.com'; await request('/auth/register', { ...body, email: otherEmail });
  const otherOtp = mail.at(-1).text.match(/\b\d{6}\b/)[0];
  await User.updateOne({ email: otherEmail }, { $set: { verificationOtpExpires: new Date(0) } });
  assert.equal((await request('/auth/verify-email', { email: otherEmail, otp: otherOtp })).status, 400);
  await User.updateOne({ email: otherEmail }, { $unset: { verificationOtpSentAt: 1 } });
  await request('/auth/resend-verification', { email: otherEmail });
  const other = await request('/auth/verify-email', { email: otherEmail, otp: mail.at(-1).text.match(/\b\d{6}\b/)[0] });
  rejectMail = true; assert.equal((await request('/auth/register', { ...body, email: 'failure@example.com' })).status, 503); rejectMail = false;
  assert.equal((await User.findOne({ email: 'failure@example.com' }).select('+verificationOtpHash')).verificationOtpHash, undefined);
  await request('/auth/register', { ...body, email: 'attempts@example.com' });
  const attemptsOtp = mail.at(-1).text.match(/\b\d{6}\b/)[0];
  for (let i = 0; i < 5; i++) assert.equal((await request('/auth/verify-email', { email: 'attempts@example.com', otp: '000000' })).status, 400);
  assert.equal((await request('/auth/verify-email', { email: 'attempts@example.com', otp: attemptsOtp })).status, 400);
  const token = verified.data.token;
  const team = await Team.create({ ownerId: verified.data.user.id, name: 'Khichuri', event: 'Hackathon', description: 'Build together', openSlots: 2 });
  const path = `/teams/${team._id}`;
  assert.equal((await request(path + '/workspace')).status, 401);
  for (const [suffix, payload, method] of [['workspace', null, 'GET'], ['messages', { text: 'intrusion' }, 'POST'], ['progress', { progressPercent: 80 }, 'PATCH'], ['assets', { title: 'No', imageUrl: 'https://example.com/a.png' }, 'POST'], ['assets/' + new mongoose.Types.ObjectId(), {}, 'DELETE']]) assert.equal((await request(path + '/' + suffix, payload, other.data.token, method)).status, 403);
  assert.equal((await request(path + '/messages', { text: 'Hello team', clientMessageId: 'test-message' }, token)).status, 201);
  assert.equal((await request(path + '/progress', { projectState: 'Building MVP', progressPercent: 50, currentSprintGoal: 'Demo', milestone: { title: 'Ship', assigneeName: 'Builder' } }, token, 'PATCH')).status, 200);
  assert.equal((await request(path + '/progress', { progressPercent: 101 }, token, 'PATCH')).status, 400);
  assert.equal((await request(path + '/assets', { title: 'Bad', imageUrl: 'javascript:alert(1)' }, token)).status, 400);
  assert.equal((await request(path + '/assets', { title: 'Diagram', caption: 'Architecture', imageUrl: 'data:image/png;base64,aGVsbG8=' }, token)).status, 201);
  let workspace = (await request(path + '/workspace', null, token)).data;
  assert.equal(workspace.messages[0].senderName, 'Builder'); assert.equal(workspace.projectState, 'Building MVP'); assert.equal(workspace.members.length, 1);
  assert.equal((await request(path + '/progress', { milestone: { _id: workspace.milestones[0]._id, completed: true } }, token, 'PATCH')).status, 200);
  assert.equal((await request(path + '/assets/' + workspace.assets[0]._id, {}, token, 'DELETE')).status, 200);
  workspace = (await request(path + '/workspace', null, token)).data; assert.equal(workspace.milestones[0].completed, true); assert.equal(workspace.assets.length, 0);
});
