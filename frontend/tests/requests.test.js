import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createApiClient } from '../src/apiClient.js';
test('GET deduplication, TTL, canonical query keys, invalidation, session isolation and failures', async () => {
  let session = 'a', time = 0; const calls = [];
  const api = createApiClient((path, options) => new Promise((resolve, reject) => calls.push({ path, options, resolve, reject })), () => session, { now: () => time });
  const first = api('/profiles?b=2&a=1'); assert.equal(api('/profiles?a=1&b=2'), first);
  await Promise.resolve(); calls.at(-1).resolve([{ value: 1 }]); await first;
  const cached = await api('/profiles?a=1&b=2'); cached[0].value = 9;
  assert.equal((await api('/profiles?b=2&a=1'))[0].value, 1); assert.equal(calls.length, 1);
  time = 21000; const expired = api('/profiles?a=1&b=2'); await Promise.resolve(); calls.at(-1).resolve([]); await expired;
  const stale = api('/connections'); await Promise.resolve(); const staleCall = calls.at(-1);
  const write = api('/invitations', { method: 'POST' }); await Promise.resolve(); calls.at(-1).resolve({}); await write;
  staleCall.resolve(['old']); await stale;
  const fresh = api('/connections'); await Promise.resolve(); assert.notEqual(calls.at(-1), staleCall); calls.at(-1).resolve(['new']); await fresh;
  session = 'b'; const another = api('/connections'); await Promise.resolve(); calls.at(-1).reject(Error('offline')); await assert.rejects(another, /offline/);
  const retry = api('/connections'); await Promise.resolve(); calls.at(-1).resolve([]); await retry;
  const chat = api('/messages/peer?after=2026-01-01'); await Promise.resolve(); calls.at(-1).resolve([]); await chat;
  const nextPoll = api('/messages/peer?after=2026-01-01'); await Promise.resolve(); calls.at(-1).resolve([]); await nextPoll;
  assert.equal(api.stats.deduplicated, 1); assert.equal(api.stats.cacheHits, 2);
});
